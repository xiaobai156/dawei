def decode_keyed_jpeg(data: bytes) -> bytes:
    if data.startswith(b"\xff\xd8"):
        return data
    if len(data) <= 8:
        raise ScrapeError("encoded image response is too short")
    key = data[:8]
    decoded = bytearray(data[8:])
    for index in range(len(decoded)):
        decoded[index] ^= key[index % len(key)]
    if not decoded.startswith(b"\xff\xd8"):
        raise ScrapeError("decoded image is not JPEG data")
    return bytes(decoded)


def bmp_to_dark_pixels(data: bytes, threshold: int = 160) -> tuple[list[list[bool]], int, int]:
    if data[:2] != b"BM":
        raise ScrapeError("image conversion did not produce BMP data")
    offset = struct.unpack_from("<I", data, 10)[0]
    width = struct.unpack_from("<i", data, 18)[0]
    height_value = struct.unpack_from("<i", data, 22)[0]
    bpp = struct.unpack_from("<H", data, 28)[0]
    if bpp not in {24, 32}:
        raise ScrapeError(f"unsupported BMP bit depth: {bpp}")

    height = abs(height_value)
    top_down = height_value < 0
    bytes_per_pixel = bpp // 8
    row_size = ((bpp * width + 31) // 32) * 4
    pixels: list[list[bool]] = []
    for y in range(height):
        source_y = y if top_down else height - 1 - y
        start = offset + source_y * row_size
        row: list[bool] = []
        for x in range(width):
            base = start + x * bytes_per_pixel
            blue, green, red = data[base : base + 3]
            row.append((red + green + blue) // 3 < threshold)
        pixels.append(row)
    return pixels, width, height


def row_groups(dark_pixels: list[list[bool]], min_dark: int = 20) -> list[tuple[int, int]]:
    groups: list[list[int]] = []
    for y, row in enumerate(dark_pixels):
        if sum(row) <= min_dark:
            continue
        if not groups or y > groups[-1][-1] + 1:
            groups.append([])
        groups[-1].append(y)
    return [(group[0], group[-1]) for group in groups]


def digit_components(
    dark_pixels: list[list[bool]],
    width: int,
    y1: int,
    y2: int,
) -> list[tuple[int, int, int, int]]:
    columns: list[int] = []
    for x in range(width):
        if any(dark_pixels[y][x] for y in range(y1, y2 + 1)):
            columns.append(x)

    column_groups: list[list[int]] = []
    for x in columns:
        if not column_groups or x > column_groups[-1][-1] + 1:
            column_groups.append([])
        column_groups[-1].append(x)

    components: list[tuple[int, int, int, int]] = []
    for column_group in column_groups:
        x1, x2 = column_group[0], column_group[-1]
        ys = [
            y
            for y in range(y1, y2 + 1)
            for x in range(x1, x2 + 1)
            if dark_pixels[y][x]
        ]
        if not ys:
            continue
        yy1, yy2 = min(ys), max(ys)
        area = sum(
            1
            for y in range(yy1, yy2 + 1)
            for x in range(x1, x2 + 1)
            if dark_pixels[y][x]
        )
        if x2 - x1 + 1 >= 5 and yy2 - yy1 + 1 >= 8 and area >= 20:
            components.append((x1, x2, yy1, yy2))
    return components


def normalize_component(
    dark_pixels: list[list[bool]],
    component: tuple[int, int, int, int],
    width: int = 8,
    height: int = 12,
) -> tuple[int, ...]:
    x1, x2, y1, y2 = component
    normalized: list[int] = []
    for yy in range(height):
        bits = 0
        source_y1 = y1 + (yy * (y2 - y1 + 1)) // height
        source_y2 = y1 + (((yy + 1) * (y2 - y1 + 1) + height - 1) // height) - 1
        for xx in range(width):
            source_x1 = x1 + (xx * (x2 - x1 + 1)) // width
            source_x2 = x1 + (((xx + 1) * (x2 - x1 + 1) + width - 1) // width) - 1
            total = 0
            dark = 0
            for source_y in range(source_y1, source_y2 + 1):
                for source_x in range(source_x1, source_x2 + 1):
                    total += 1
                    dark += dark_pixels[source_y][source_x]
            if dark * 2 >= total:
                bits |= 1 << (width - 1 - xx)
        normalized.append(bits)
    return tuple(normalized)


def template_distance(left: tuple[int, ...], right: tuple[int, ...]) -> int:
    return sum((left_row ^ right_row).bit_count() for left_row, right_row in zip(left, right))


def classify_digit(pattern: tuple[int, ...]) -> str:
    best_digit = ""
    best_distance: int | None = None
    for digit, templates in OCR_DIGIT_TEMPLATES.items():
        distance = min(template_distance(pattern, template) for template in templates)
        if best_distance is None or distance < best_distance:
            best_digit = digit
            best_distance = distance
    if best_distance is None or best_distance > 45:
        raise ScrapeError("failed to recognize a digit from image")
    return best_digit


def extract_fixed_image_numbers(bmp: bytes) -> tuple[str, ...]:
    dark_pixels, width, _ = bmp_to_dark_pixels(bmp)
    groups = row_groups(dark_pixels)
    if len(groups) < 3:
        raise ScrapeError("image did not contain enough text rows")

    digits: list[str] = []
    for y1, y2 in groups[-2:]:
        components = digit_components(dark_pixels, width, y1, y2)
        if len(components) != 36:
            raise ScrapeError(f"expected 36 digit components in image row, got {len(components)}")
        for component in components:
            digits.append(classify_digit(normalize_component(dark_pixels, component)))

    numbers = tuple("".join(digits[index : index + 2]) for index in range(0, len(digits), 2))
    if not valid_36_code_record(numbers):
        raise ScrapeError("图片识别号码无效: " + invalid_36_code_reason(numbers))
    return numbers


def bb48kk_images_from(html: str) -> list[tuple[int, str, bool]]:
    images: list[tuple[int, str, bool]] = []
    for tag_match in IMG_TAG_RE.finditer(html):
        tag = tag_match.group(0)
        id_match = BB48KK_ID_RE.search(tag)
        url_match = DATA_OPT_URL_RE.search(tag)
        if not id_match or not url_match:
            continue
        compact_tag = re.sub(r"\s+", "", tag).lower()
        images.append((int(id_match.group(1)), url_match.group(1), "display:block" in compact_tag))
    return images
